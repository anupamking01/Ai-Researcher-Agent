"""Synthetic regression checks for post-expiry offline preservation replay.

No original treatments or human ratings are generated by these fixtures.
"""
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path

import pytest

from scripts import verify_preserved_canonical_bundle as replay
from scripts import verify_retained_canonical_download as source

CAPTURED_AT = datetime(2026, 10, 29, tzinfo=timezone.utc)
AFTER_EXPIRY = datetime(2027, 1, 1, tzinfo=timezone.utc)


def _bundle(tmp_path, monkeypatch):
    raw_zip = tmp_path / "retained-canonical.zip"
    raw_zip.write_bytes(b"synthetic fixture only, not a real canonical ZIP")
    digest = hashlib.sha256(raw_zip.read_bytes()).hexdigest()
    monkeypatch.setattr(source, "OBSERVED_ZIP_BYTES", raw_zip.stat().st_size)
    monkeypatch.setattr(source, "OBSERVED_ZIP_SHA256", digest)

    meta = {
        "id": source.ARTIFACT_ID,
        "name": source.ARTIFACT_NAME,
        "expired": False,
        "expires_at": "2026-12-23T23:03:46Z",
        "size_in_bytes": source.OBSERVED_ZIP_BYTES,
        "digest": "sha256:" + digest,
        "archive_download_url": (
            f"https://api.github.com/repos/{source.REPO}/actions/artifacts/"
            f"{source.ARTIFACT_ID}/zip"
        ),
        "workflow_run": {
            "id": source.RUN_ID,
            "head_sha": source.RUN_HEAD,
            "head_branch": "research-paper-eval-2027",
            "repository_id": source.REPO_ID,
            "head_repository_id": source.REPO_ID,
        },
    }
    metadata_path = tmp_path / "canonical-source-metadata.json"
    metadata_path.write_text(json.dumps(meta), encoding="utf-8")

    def checked(zip_path, *, root):
        assert Path(zip_path) == raw_zip
        return {
            "archive_sha256_observed_now": digest,
            "historical_evidence_authenticated": False,
            "original_treatment_traces_authenticated": False,
            "human_evaluation_ready": False,
            "independently_supplied_archive_pin_matched": False,
        }
    monkeypatch.setattr(source.concordance, "verify_archive_against_checkout", checked)

    original = source.verify_download(metadata_path, raw_zip, checked_at=CAPTURED_AT)
    receipt_path = tmp_path / "retained-canonical-verification.json"
    receipt_path.write_text(json.dumps(original), encoding="utf-8")
    return metadata_path, raw_zip, receipt_path


def _recheck(paths, *, checked_at=AFTER_EXPIRY):
    return replay.verify_preserved_bundle(*paths, checked_at=checked_at)


def test_preserved_bundle_is_verifiable_after_original_artifact_expires(
    tmp_path, monkeypatch,
):
    paths = _bundle(tmp_path, monkeypatch)
    result = _recheck(paths)
    assert result["status"] == (
        "offline_preserved_canonical_bundle_reverified_not_independent_custody"
    )
    assert result["source_expiry_time_passed_at_reverification"] is True
    assert result["original_github_source_availability_checked"] is False
    assert result["saved_receipt_exactly_recomputed"] is True
    assert result["independent_historical_custody_authenticated"] is False
    assert result["original_treatment_traces_authenticated"] is False
    assert result["human_evaluation_ready"] is False


def test_default_live_source_audit_still_rejects_expired_artifact(
    tmp_path, monkeypatch,
):
    paths = _bundle(tmp_path, monkeypatch)
    with pytest.raises(ValueError, match="expiry has elapsed"):
        source.verify_download(paths[0], paths[1], checked_at=AFTER_EXPIRY)


def test_offline_replay_before_expiry_reports_current_clock_accurately(
    tmp_path, monkeypatch,
):
    paths = _bundle(tmp_path, monkeypatch)
    result = _recheck(paths, checked_at=CAPTURED_AT)
    assert result["source_expiry_time_passed_at_reverification"] is False


@pytest.mark.parametrize("field,value", [
    ("independent_historical_custody_authenticated", True),
    ("original_treatment_traces_authenticated", True),
    ("human_evaluation_ready", True),
    ("source_artifact_id", 1),
    ("schema_version", True),  # In Python, True == 1; JSON types must differ.
])
def test_tampered_saved_receipt_fails_closed(tmp_path, monkeypatch, field, value):
    paths = _bundle(tmp_path, monkeypatch)
    saved = json.loads(paths[2].read_text())
    saved[field] = value
    paths[2].write_text(json.dumps(saved), encoding="utf-8")
    with pytest.raises(ValueError, match="preserved verification receipt differs"):
        _recheck(paths)


def test_added_saved_receipt_field_is_rejected(tmp_path, monkeypatch):
    paths = _bundle(tmp_path, monkeypatch)
    saved = json.loads(paths[2].read_text())
    saved["unverified_provenance_claim"] = "trusted"
    paths[2].write_text(json.dumps(saved), encoding="utf-8")
    with pytest.raises(ValueError, match="receipt differs"):
        _recheck(paths)


def test_duplicate_receipt_json_key_is_rejected(tmp_path, monkeypatch):
    paths = _bundle(tmp_path, monkeypatch)
    text = paths[2].read_text()
    paths[2].write_text(text.replace('"schema_version": 1',
                                   '"schema_version": 5, "schema_version": 1', 1))
    with pytest.raises(ValueError, match="duplicate GitHub metadata JSON key"):
        _recheck(paths)


def test_expired_offline_replay_still_rejects_archive_tampering(
    tmp_path, monkeypatch,
):
    paths = _bundle(tmp_path, monkeypatch)
    paths[1].write_bytes(b"x" * paths[1].stat().st_size)
    with pytest.raises(ValueError, match="ZIP bytes differ"):
        _recheck(paths)


def test_expired_offline_replay_still_checks_capture_metadata(
    tmp_path, monkeypatch,
):
    paths = _bundle(tmp_path, monkeypatch)
    metadata = json.loads(paths[0].read_text())
    metadata["workflow_run"]["head_sha"] = "0" * 40
    paths[0].write_text(json.dumps(metadata), encoding="utf-8")
    with pytest.raises(ValueError, match="historical workflow identity differs"):
        _recheck(paths)


def test_oversized_preserved_receipt_rejected_before_checkout(
    tmp_path, monkeypatch,
):
    paths = _bundle(tmp_path, monkeypatch)
    monkeypatch.setattr(replay, "MAX_PRESERVED_RECEIPT_BYTES", 20)
    with pytest.raises(ValueError, match="preserved verification receipt exceeds byte limit"):
        _recheck(paths)


def test_preserved_receipt_must_be_regular_file(tmp_path, monkeypatch):
    paths = _bundle(tmp_path, monkeypatch)
    link = tmp_path / "receipt-link.json"
    link.symlink_to(paths[2])
    with pytest.raises(ValueError, match="must be a regular file"):
        _recheck((paths[0], paths[1], link))


def test_offline_replay_rejects_naive_recheck_datetime(tmp_path, monkeypatch):
    paths = _bundle(tmp_path, monkeypatch)
    with pytest.raises(ValueError, match="timezone-aware"):
        _recheck(paths, checked_at=datetime(2027, 1, 1))
